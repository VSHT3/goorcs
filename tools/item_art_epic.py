def _paint(commands, detail):
    image, draw = portrait() if detail else canvas()
    edge = 2 if detail else 1
    for command in commands:
        kind, color, geometry, *extra = command
        color = _COLORS.get(color, color)
        if kind in ("p", "P"):
            poly(draw, geometry, color, outline=INK if kind == "p" else None, width=edge)
        elif kind in ("r", "R", "e", "E"):
            shape = draw.rectangle if kind.lower() == "r" else draw.ellipse
            shape(geometry, fill=color, outline=INK if kind.islower() else None, width=edge)
        elif kind == "l":
            line(draw, geometry, color, extra[0] if extra else 1)
        elif kind == "a":
            draw.arc(geometry, start=extra[0], end=extra[1], fill=color, width=extra[2])
        elif kind == "q":
            for point in geometry:
                draw.point(point, fill=color)
        elif kind == "s":
            skull(draw, *geometry, color=color)
    return image


def _art(icon, detail):
    def small():
        return _paint(icon, False)

    def large():
        return _paint(detail, True)

    return small, large


